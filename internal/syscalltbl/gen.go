//go:build ignore

// gen.go writes pkg/collector/syscall_names_gen.go from the kernel's own
// syscall tables, kept beside it as amd64.tbl and arm64.tbl (#139).
//
//	go generate ./pkg/collector          # regenerate from the committed tables
//	make syscalls                        # re-fetch them at kernelTag, then regenerate
//
// The tables are committed rather than fetched at build time, so a build needs
// neither the network nor the libc headers; only -fetch touches the network.
// They are also what TestSyscallNamesCoverKernelTables reads back, which is why
// they live in the tree and not in a temporary directory.
//
// To move the pin, change kernelTag and run `make syscalls`.
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"io"
	"net/http"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"time"
)

// kernelTag is the Linux release the committed tables were taken from.
const kernelTag = "v7.2"

// arch is one table: where the kernel keeps it, and which of its ABI columns
// make up the 64-bit native syscall set that raw_syscalls reports for a 64-bit
// process on that architecture.
type arch struct {
	goarch   string
	varName  string
	upstream string   // path inside the kernel tree
	abis     []string // the kernel's own syscall_abis_64 for this arch
}

var arches = []arch{
	{
		// x32 entries (512-547) are excluded: an x32 process reports them with
		// __X32_SYSCALL_BIT set, so they never collide with these numbers.
		goarch:   "amd64",
		varName:  "syscallsAMD64",
		upstream: "arch/x86/entry/syscalls/syscall_64.tbl",
		abis:     []string{"common", "64"},
	},
	{
		// The generic table. arch/arm64/kernel/Makefile.syscalls points at
		// arch/arm64/tools/syscall_64.tbl, which is a symlink to this file; a
		// raw fetch of the symlink returns the link, not the table.
		// scripts/Makefile.asm-headers sets syscall_abis_64 to common,64 and
		// arm64's Makefile.syscalls adds the other three.
		goarch:   "arm64",
		varName:  "syscallsARM64",
		upstream: "scripts/syscall.tbl",
		abis:     []string{"common", "64", "renameat", "rlimit", "memfd_secret"},
	},
}

func main() {
	fetch := flag.Bool("fetch", false, "download the tables at "+kernelTag+" before generating (needs network)")
	flag.Parse()

	root, err := moduleRoot()
	if err != nil {
		fail(err)
	}
	dir := filepath.Join(root, "internal", "syscalltbl")

	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by internal/syscalltbl/gen.go from Linux %s; DO NOT EDIT.\n//\n", kernelTag)
	for _, a := range arches {
		fmt.Fprintf(&out, "// %s: %s, ABIs %s\n", a.goarch, a.upstream, strings.Join(a.abis, ","))
	}
	out.WriteString("\npackage collector\n")

	for _, a := range arches {
		path := filepath.Join(dir, a.goarch+".tbl")
		if *fetch {
			if err := download(a.upstream, path); err != nil {
				fail(err)
			}
		}
		names, err := parse(path, a.abis)
		if err != nil {
			fail(err)
		}
		writeTable(&out, a, names)
	}

	src, err := format.Source(out.Bytes())
	if err != nil {
		fail(fmt.Errorf("gofmt generated source: %w", err))
	}
	dst := filepath.Join(root, "pkg", "collector", "syscall_names_gen.go")
	if err := os.WriteFile(dst, src, 0o644); err != nil {
		fail(err)
	}
}

// parse reads a syscall.tbl — `<nr> <abi> <name> [<entry> [<compat>]]` — and
// keeps the entries whose ABI is in abis. One number may carry several lines
// (a 32-bit and a 64-bit variant); exactly one may survive the filter.
func parse(path string, abis []string) (map[int]string, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	want := make(map[string]bool, len(abis))
	for _, a := range abis {
		want[a] = true
	}
	names := make(map[int]string)
	sc := bufio.NewScanner(f)
	for line := 1; sc.Scan(); line++ {
		fields := strings.Fields(sc.Text())
		if len(fields) == 0 || strings.HasPrefix(fields[0], "#") {
			continue
		}
		if len(fields) < 3 {
			return nil, fmt.Errorf("%s:%d: want <nr> <abi> <name>, got %q", path, line, sc.Text())
		}
		if !want[fields[1]] {
			continue
		}
		nr, err := strconv.Atoi(fields[0])
		if err != nil {
			return nil, fmt.Errorf("%s:%d: %w", path, line, err)
		}
		if prev, dup := names[nr]; dup {
			return nil, fmt.Errorf("%s:%d: %d is both %s and %s for ABIs %v", path, line, nr, prev, fields[2], abis)
		}
		names[nr] = fields[2]
	}
	return names, sc.Err()
}

func writeTable(out *bytes.Buffer, a arch, names map[int]string) {
	nrs := make([]int, 0, len(names))
	for nr := range names {
		nrs = append(nrs, nr)
	}
	sort.Ints(nrs)
	fmt.Fprintf(out, "\n// %s is indexed by syscall number; \"\" marks a number the table leaves unassigned.\n", a.varName)
	fmt.Fprintf(out, "var %s = [...]string{\n", a.varName)
	for _, nr := range nrs {
		fmt.Fprintf(out, "\t%d: %q,\n", nr, names[nr])
	}
	out.WriteString("}\n")
}

func download(upstream, dst string) error {
	url := "https://raw.githubusercontent.com/torvalds/linux/" + kernelTag + "/" + upstream
	client := &http.Client{Timeout: 60 * time.Second}
	resp, err := client.Get(url)
	if err != nil {
		return err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return fmt.Errorf("GET %s: %s", url, resp.Status)
	}
	body, err := io.ReadAll(resp.Body)
	if err != nil {
		return err
	}
	return os.WriteFile(dst, body, 0o644)
}

// moduleRoot walks up from the working directory to go.mod, so the generator
// runs the same from `go generate` (in pkg/collector) and from the Makefile.
func moduleRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("no go.mod above %s", dir)
		}
		dir = parent
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "syscalltbl:", err)
	os.Exit(1)
}
